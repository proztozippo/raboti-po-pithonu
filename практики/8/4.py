"""
m – стартовое количество организмов;
p – среднесуточное увеличение в процентах;
n – количество дней для размножения.
"""

m = int(input("введите стартовое количество организмов: "))
p = int(input("введите среднесуточное увеличение в процентах организмов: "))
n = int(input("введите количество дней для размножения: "))
print(f"в {n} день {m} организмов ")
for i in range(2, n + 1):
    m += m * (0.01 * p)
    m = int(m)
    print(f"в {n} день {m} организмов ")